// Builds Turn's two language pages from one bilingual source.
//   scripts/turn-i18n/page.html     — page shell; sections are pulled in with {{@part:name}}
//   scripts/turn-i18n/parts/*.html  — one file per section, each owned by one part of the page
//   bilingual text is written as {{ 中文 ‖ English }} anywhere in the shell or the parts
//   {{@letter:word}} / {{@letter:word|class}} inlines a hand-lettered word (scripts/turn-lettering.mjs)
// Output: public/turn/index.html (zh) and public/turn/en/index.html (en), with ?v= content hashes on every
// local CSS/JS reference. `--check` fails when the committed pages differ from a fresh build.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { root } from './catalog.mjs';
import { letteringSvg } from './turn-lettering.mjs';

const src = path.join(root, 'scripts/turn-i18n');
const out = path.join(root, 'public/turn');
const origin = 'https://interviewhacker.vercel.app';
const langs = {
  zh: { file: 'index.html', base: './', html: 'zh-CN', url: `${origin}/turn/`, other: './en/', hrefZh: './', hrefEn: './en/' },
  en: { file: 'en/index.html', base: '../', html: 'en', url: `${origin}/turn/en/`, other: '../', hrefZh: '../', hrefEn: './' }
};

const hashOf = async file => createHash('sha256').update(await readFile(file)).digest('hex').slice(0, 12);

async function loadParts() {
  const parts = {};
  for (const name of (await readdir(path.join(src, 'parts'))).filter(n => n.endsWith('.html')).sort()) {
    parts[name.replace(/\.html$/, '')] = await readFile(path.join(src, 'parts', name), 'utf8');
  }
  return parts;
}

export async function render(lang) {
  const L = langs[lang];
  const parts = await loadParts();
  let html = (await readFile(path.join(src, 'page.html'), 'utf8'))
    .replace(/\{\{@part:([a-z0-9-]+)\}\}/g, (_, name) => {
      if (!(name in parts)) throw new Error(`Missing part: ${name}`);
      return parts[name].trim();
    });
  html = html
    // Bilingual text. Either side may be empty; neither may contain {{ }} or ‖.
    .replace(/\{\{\s*([^{}‖]*?)\s*‖\s*([^{}‖]*?)\s*\}\}/g, (_, zh, en) => lang === 'zh' ? zh : en)
    .replace(/\{\{@letter:([a-z .,'!?-]+?)(?:\|([a-z0-9 _-]+))?\}\}/gi, (_, word, cls) => letteringSvg({ word, className: `lettering ${cls || ''}`.trim() }))
    .replaceAll('{{base}}', L.base)
    .replaceAll('{{lang}}', L.html)
    .replaceAll('{{url}}', L.url)
    .replaceAll('{{url-zh}}', langs.zh.url)
    .replaceAll('{{url-en}}', langs.en.url)
    .replaceAll('{{other}}', L.other)
    .replaceAll('{{href-zh}}', L.hrefZh)
    .replaceAll('{{href-en}}', L.hrefEn)
    .replaceAll('{{attr-zh}}', lang === 'zh' ? ' aria-current="page"' : ' data-lang-switch')
    .replaceAll('{{attr-en}}', lang === 'en' ? ' aria-current="page"' : ' data-lang-switch');
  const left = html.match(/\{\{[^}]*\}\}/);
  if (left) throw new Error(`Unresolved template token in ${lang}: ${left[0]}`);
  for (const m of [...html.matchAll(/((?:href|src)=")(\.\.?\/)([^"?#]+\.(?:css|js))"/g)]) {
    const file = path.join(out, m[3]);
    html = html.replace(m[0], `${m[1]}${m[2]}${m[3]}?v=${await hashOf(file)}"`);
  }
  return `<!-- Generated by scripts/build-turn.mjs from scripts/turn-i18n/. Edit the source, then run npm run turn:build. -->\n${html}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const lang of Object.keys(langs)) {
    const file = path.join(out, langs[lang].file);
    const html = await render(lang);
    if (check) {
      const current = await readFile(file, 'utf8').catch(() => '');
      if (current !== html) { console.error(`Turn ${lang} page is stale: run npm run turn:build`); stale = true; }
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, html);
    }
  }
  if (stale) process.exit(1);
  console.log(check ? 'Turn pages are up to date' : 'Turn pages written');
}

// Signature has one bilingual source. Generated HTML is committed for static hosting.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { root } from './catalog.mjs';
import { letteringSvg } from './turn-lettering.mjs';

const source = path.join(root, 'scripts/signature-i18n');
const output = path.join(root, 'public/signature');
const origin = 'https://interviewhacker.vercel.app';
const languages = {
  zh: { file: 'index.html', base: './', html: 'zh-CN', route: '/signature/', other: './en/', otherName: 'EN', source: 'signature' },
  en: { file: 'en/index.html', base: '../', html: 'en', route: '/signature/en/', other: '../', otherName: '中文', source: 'signature-en' }
};

export async function render(lang) {
  const L = languages[lang];
  let page = await readFile(path.join(source, 'page.html'), 'utf8');
  for (const file of (await readdir(path.join(source, 'parts'))).filter(f => f.endsWith('.html'))) {
    page = page.replaceAll(`{{@part:${file.slice(0, -5)}}}`, (await readFile(path.join(source, 'parts', file), 'utf8')).trim());
  }
  page = page.replace(/\{\{\s*([^{}‖]*?)\s*‖\s*([^{}‖]*?)\s*\}\}/g, (_, zh, en) => lang === 'zh' ? zh : en)
    .replace(/\{\{@letter:([a-z .,'!?-]+)\}\}/gi, (_, word) => letteringSvg({ word, className: 'handwritten' }));
  for (const [key, value] of Object.entries({ ...L, url: origin + L.route, 'url-zh': origin + languages.zh.route, 'url-en': origin + languages.en.route, 'data-lang': lang })) page = page.replaceAll(`{{${key}}}`, value);
  const data = JSON.parse(await readFile(path.join(source, 'demo.json'), 'utf8'))[lang];
  page = page.replace('{{@data}}', JSON.stringify(data).replace(/</g, '\\u003c'));
  if (/\{\{/.test(page)) throw new Error(`Unresolved Signature template: ${page.match(/\{\{[^}]+\}\}/)?.[0]}`);
  for (const match of [...page.matchAll(/((?:href|src)=")(\.\.?\/)([^"?#]+\.(?:css|js))"/g)]) {
    const hash = createHash('sha256').update(await readFile(path.join(output, match[3]))).digest('hex').slice(0, 12);
    page = page.replace(match[0], `${match[1]}${match[2]}${match[3]}?v=${hash}"`);
  }
  return '<!-- Generated by scripts/build-signature.mjs. Edit scripts/signature-i18n/, then npm run signature:build. -->\n' + page;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  for (const [lang, L] of Object.entries(languages)) {
    const html = await render(lang), file = path.join(output, L.file);
    if (check) {
      if (await readFile(file, 'utf8').catch(() => '') !== html) throw new Error(`Signature ${lang} is stale; run npm run signature:build`);
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, html);
    }
  }
  console.log(check ? 'Signature pages are up to date' : 'Signature bilingual pages written');
}

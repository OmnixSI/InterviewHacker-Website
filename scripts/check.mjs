import { readFile, access } from 'node:fs/promises';
import assert from 'node:assert/strict';
const publicRoot = new URL('../public/', import.meta.url);
const html = await readFile(new URL('index.html', publicRoot), 'utf8');
const css = await readFile(new URL('style.css', publicRoot), 'utf8');
const js = await readFile(new URL('app.js', publicRoot), 'utf8');
for (const file of ['engine.js','font-license.txt','og.png']) await access(new URL(file, publicRoot));
assert(!/Paddle|Qwen|Codex|DeepSeek|OpenAI/.test(html.slice(0,html.indexOf('<section id="faq"'))), 'Vendor names should not dominate product storytelling');
for (const id of ['signal-field','story-field','tech-panel','inject-signal']) assert(html.includes(`id="${id}"`));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length, new Set(ids).size, 'IDs must be unique');
for (const m of html.matchAll(/(?:src|href)="(\/[^"]+)"/g)) await access(new URL(m[1].slice(1), publicRoot));
for (const m of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(m[1]), `Missing anchor ${m[1]}`);
for (const m of js.matchAll(/image: '([^']+)'/g)) await access(new URL('shots/'+m[1], publicRoot));
for (const text of ['v1.8.0','需要仓库访问权','不会把所有资料塞入上下文','语音识别 + 对话服务','交互示意']) assert(html.includes(text), `Missing product disclosure: ${text}`);
assert.equal((html.match(/<h1\b/g)||[]).length, 1);
assert(css.includes('prefers-reduced-motion'));
assert(!/fonts\.googleapis|mcode\.cn|v1\.7\.0|无法被检测|<sup>®/.test(html));
const staticConfig = JSON.parse(await readFile(new URL('vercel.json', publicRoot), 'utf8'));
const gitConfig = JSON.parse(await readFile(new URL('../vercel.json', publicRoot), 'utf8'));
assert.deepEqual(gitConfig.headers, staticConfig.headers, 'Git and static deployments must share response headers');
assert.equal(gitConfig.outputDirectory, 'dist');
console.log('Static references, anchors, product disclosures and deployment configuration passed.');
